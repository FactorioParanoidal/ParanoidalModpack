-- Production achievements from MxlChievements, one line per series.
--   [1] name prefix: achievements are <prefix>-1, <prefix>-2, ... (just <prefix> with single = true)
--   [2] item to produce; defaults to the prefix
--   [3] picture in graphics/ without ".png", "%d" is replaced by the tier; without a picture
--       the tiers use bronze/silver/gold frames around the product icon
--   amounts   thresholds per tier, default 1M / 1G / 1T
--   per_hour  produce-per-hour-achievement instead of produce-achievement
--   fluid     fluid to produce instead of an item
--   quality   only this quality counts; "normal" is dropped and other qualities are skipped
--             when the quality mod is off
--   train     minimum lengths of a train path: a train-path-achievement series
--   product_icon  picture used instead of the product icon inside the frame
-- Missing or hidden products are skipped, so the list can name items of optional mods.
--
-- Not included because the base game ladders in base-series.lua already cover the same
-- product and range: green-card (mass-production), iron-madness (iron-throne),
-- big-red-machine (circuit-veteran), keep-on-smurfin (computer-age).

local function steps(step, count)
  local amounts = {}
  for tier = 1, count do amounts[tier] = step * tier end
  return amounts
end

