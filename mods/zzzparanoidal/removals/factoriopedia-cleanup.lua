local missing = 0
for type_name, names in pairs(hide) do
	local protos = data.raw[type_name] or {}
	for _, name in ipairs(names) do
		local proto = protos[name]
		if proto then
			proto.hidden_in_factoriopedia = true
		else
			missing = missing + 1
		end
	end
end

for type_name, targets in pairs(redirect) do
	local protos = data.raw[type_name] or {}
	for name, target in pairs(targets) do
		local proto = protos[name]
		if proto and protos[target] then
			proto.factoriopedia_alternative = target
		else
			missing = missing + 1
		end
	end
end

if missing > 0 then
	log("factoriopedia-cleanup: skipped absent prototypes: " .. missing)
end

