-- Preview

local COLORS = {
    free = {r = 0, g = 0.45, b = 0, a = 0.35},
    forced = {r = 0.55, g = 0.3, b = 0, a = 0.4},
    kept = {r = 0.5, g = 0, b = 0, a = 0.35},
}

local function clear_preview(job)
    for _, object in pairs(job.renders or {}) do
        if object.valid then object.destroy() end
    end
    job.renders = {}
end

-- Rectangles over the chunks, a run of neighbouring chunks of a row in one rectangle, on the map
-- and in the world, seen only by the player.
local function draw_preview(job, list)
    local player = game.get_player(job.player_index)
    if not player then return end
    table.sort(list, function(a, b)
        if a.y ~= b.y then return a.y < b.y end
        return a.x < b.x
    end)
    local renders = job.renders
    local function draw(run)
        for _, mode in ipairs({"game", "chart"}) do
            renders[#renders + 1] = rendering.draw_rectangle{
                color = COLORS[run.color], filled = true, draw_on_ground = true, render_mode = mode,
                left_top = {run.x1 * 32, run.y * 32}, right_bottom = {run.x2 * 32 + 32, run.y * 32 + 32},
                surface = job.surface_index, players = {player},
            }
        end
    end
    local run
    for _, c in ipairs(list) do
        if run and run.y == c.y and run.x2 == c.x - 1 and run.color == c.color then
            run.x2 = c.x
        else
            if run then draw(run) end
            run = {x1 = c.x, x2 = c.x, y = c.y, color = c.color}
        end
    end
    if run then draw(run) end
end

---------------------------------------------------------------------------------------------------
-- Dialog

local function close_dialog(player)
    local frame = player.gui.screen[GUI]
    if frame then frame.destroy() end
end

local function summary(job)
    local s = job.stats
    local lines = {}
    local function add(...) lines[#lines + 1] = {...} end
    if job.mode == "trim" then
        local surface = game.get_surface(job.surface_index)
        add("dct.trim-found", #job.chunks, job.distance, surface and surface.name or "?")
    else
        add("dct.found", #job.chunks)
    end
    if job.mode == "force" then
        if s.owned > 0 then add("dct.forced-owned", s.owned) end
        if s.ruins > 0 then add("dct.forced-ruins", s.ruins) end
        if s.legendary > 0 then add("dct.forced-legendary", s.legendary) end
        if s.character > 0 then add("dct.kept-character", s.character) end
    elseif job.mode == "tool" then
        local kept = s.owned + s.ruins + s.legendary + s.character
        if kept > 0 then
            add("dct.kept", kept, s.owned + s.character, s.ruins, s.legendary)
            add("dct.hint-force")
        end
    end
    if job.chunks[1] then add(job.mode == "trim" and "dct.after-trim" or "dct.after-tool") end
    return lines
end

local function open_dialog(player, job)
    close_dialog(player)
    local frame = player.gui.screen.add{type = "frame", name = GUI, direction = "vertical",
        caption = {job.mode == "trim" and "dct.title-trim" or "dct.title"}}
    frame.auto_center = true
    local body = frame.add{type = "flow", direction = "vertical"}
    body.style.maximal_width = 520
    for _, line in ipairs(summary(job)) do
        local label = body.add{type = "label", caption = line}
        label.style.single_line = false
        label.style.maximal_width = 500
    end
    local buttons = frame.add{type = "flow", direction = "horizontal"}
    buttons.style.top_margin = 8
    buttons.add{type = "button", name = "dct_cancel", style = "back_button", caption = {"dct.cancel"}}
    local filler = buttons.add{type = "empty-widget"}
    filler.style.horizontally_stretchable = true
    if job.chunks[1] then
        buttons.add{type = "button", name = "dct_delete", style = "red_confirm_button",
            caption = {"dct.delete", #job.chunks}}
    end
end

