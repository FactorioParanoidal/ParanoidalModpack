-- Regeneration

local function snapshot_ore(surface, positions)
    local ore = per_surface(storage.ore, surface.index)
    for _, c in pairs(positions) do
        local k = key(c.x, c.y)
        if ore[k] == nil then
            local totals
            for _, entity in pairs(surface.find_entities_filtered{area = chunk_area(c.x, c.y), type = "resource"}) do
                if inside(entity.position, c.x, c.y) then
                    totals = totals or {}
                    totals[entity.name] = (totals[entity.name] or 0) + entity.amount
                end
            end
            ore[k] = totals or 0
        end
    end
end

-- Cuts the regenerated ore of the chunk down to what it had before deletion.
local function cap_ore(surface, x, y, totals)
    local by_name = {}
    for _, entity in pairs(surface.find_entities_filtered{area = chunk_area(x, y), type = "resource"}) do
        if inside(entity.position, x, y) then
            local list = by_name[entity.name]
            if not list then
                list = {sum = 0}
                by_name[entity.name] = list
            end
            list[#list + 1] = entity
            list.sum = list.sum + entity.amount
        end
    end
    for name, list in pairs(by_name) do
        local limit = totals ~= 0 and totals[name] or 0
        if list.sum > limit then
            local ratio = limit / list.sum
            local proto = prototypes.entity[name]
            local infinite = proto.infinite_resource
            local minimum = infinite and math.max(1, proto.minimum_resource_amount) or 1
            for _, entity in ipairs(list) do
                local amount = floor(entity.amount * ratio)
                if infinite and limit > 0 then
                    entity.amount = math.max(minimum, amount)
                elseif amount >= 1 then
                    entity.amount = amount
                else
                    entity.destroy()
                end
            end
        end
    end
end

local function clear_enemies(surface, x, y, forces)
    if #forces.enemies == 0 then return end
    for _, entity in pairs(surface.find_entities_filtered{area = chunk_area(x, y), force = forces.enemies, type = ENEMY_TYPES}) do
        if entity.valid and inside(entity.position, x, y) then entity.destroy{raise_destroy = true} end
    end
end

local function on_chunk_generated(event)
    local surface = event.surface
    local marks = storage.marks[surface.index]
    local c = event.position
    local value = marks and marks[key(c.x, c.y)]
    if not value then return end
    if value == CLEAN then clear_enemies(surface, c.x, c.y, force_sets()) end
    local ore = storage.ore[surface.index]
    local totals = ore and ore[key(c.x, c.y)]
    if totals ~= nil then
        cap_ore(surface, c.x, c.y, totals)
        ore[key(c.x, c.y)] = nil
    end
    local trimmed = storage.trimmed[surface.index]
    if trimmed then trimmed[key(c.x, c.y)] = nil end
end

local function on_pre_chunk_deleted(event)
    local surface = game.get_surface(event.surface_index)
    if surface then snapshot_ore(surface, event.positions) end
end

-- Chunks deleted by other mods or the console are remembered too (without clearing enemies).
local function on_chunk_deleted(event)
    for _, c in pairs(event.positions) do mark(event.surface_index, c.x, c.y, AS_GENERATED) end
end

local function forget_surface(event)
    local index = event.surface_index
    storage.marks[index], storage.ore[index], storage.trimmed[index] = nil, nil, nil
    for player_index, job in pairs(storage.jobs) do
        if job.surface_index == index then cancel_job(player_index) end
    end
end

