-- Players

local function is_admin(player)
    if player.admin or not game.is_multiplayer() then return true end
    player.print({"dct.not-admin"})
    return false
end

local function on_selected_area(event, mode)
    if event.item ~= TOOL then return end
    local player = game.get_player(event.player_index)
    if not (player and is_admin(player)) then return end
    local surface = event.surface
    local area = event.area
    local x1, y1 = floor(area.left_top.x / 32), floor(area.left_top.y / 32)
    local x2 = math.max(x1, floor((area.right_bottom.x - 0.01) / 32))
    local y2 = math.max(y1, floor((area.right_bottom.y - 0.01) / 32))
    if (x2 - x1 + 1) * (y2 - y1 + 1) > MAX_SELECTION then
        player.print({"dct.too-large", MAX_SELECTION})
        return
    end
    local job = new_job(player, surface, mode)
    for y = y1, y2 do
        for x = x1, x2 do
            local c = {x = x, y = y}
            if surface.is_chunk_generated(c) then job.todo[#job.todo + 1] = c end
        end
    end
    run(job)
end

-- Surfaces made by the map generator; factory floors, labs, platforms and service surfaces are
-- never trimmed.
local function trimmable(surface)
    return surface.planet ~= nil and surface.platform == nil and not surface.name:find("factory%-floor")
end

local function start_trim(player, distance)
    if not is_admin(player) then return end
    local surface = player.surface
    if not trimmable(surface) then
        player.print({"dct.trim-surface"})
        return
    end
    local job = new_job(player, surface, "trim")
    job.distance = distance or settings.global["dct-trim-distance"].value
    job.seeds = {}
    for c in surface.get_chunks() do
        if surface.is_chunk_generated(c) then job.todo[#job.todo + 1] = {x = c.x, y = c.y} end
    end
    player.print({"dct.trim-scan", #job.todo})
    run(job)
end

local function confirm(player)
    local job = storage.jobs[player.index]
    close_dialog(player)
    if not (job and job.state == "preview") then return end
    if not is_admin(player) then return cancel_job(player.index) end
    job.state = "delete"
    job.i, job.deleted, job.skipped = 1, 0, 0
    job.forces = force_sets()
    job.rects = legendary_rects(job.surface_index)
    run(job)
end

