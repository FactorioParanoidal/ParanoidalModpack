-- Storage

local function init_storage()
    storage.marks = storage.marks or {}       -- surface index -> chunk key -> AS_GENERATED/CLEAN
    storage.ore = storage.ore or {}           -- surface index -> chunk key -> {resource name -> amount} | 0
    storage.jobs = storage.jobs or {}         -- player index -> job
    storage.trimmed = storage.trimmed or {}   -- surface index -> chunk key -> true (recent trims)
end

---------------------------------------------------------------------------------------------------
-- Forces

-- {owned = force names of players and their allies, ruins = ruin force names, enemies = names}
local function force_sets()
    local owned, ruins, enemies = {}, {}, {}
    for _, force in pairs(game.forces) do
        local name = force.name
        if RUIN_FORCES[name] then
            ruins[#ruins + 1] = name
        elseif name == "enemy" or force.ai_controllable then
            enemies[#enemies + 1] = name
        elseif name ~= "neutral" then
            owned[#owned + 1] = name
        end
    end
    return {owned = owned, ruins = ruins, enemies = enemies}
end

---------------------------------------------------------------------------------------------------
-- Classification of a chunk

-- chunk rectangles {x1, y1, x2, y2} of the legendary ruins that are not lost yet
local function legendary_rects(surface_index)
    local iface = remote.interfaces["AbandonedRuins-paranoidal"]
    if not (iface and iface.legendary_chunks) then return {} end
    return remote.call("AbandonedRuins-paranoidal", "legendary_chunks", surface_index) or {}
end

local function in_rects(rects, x, y)
    for i = 1, #rects do
        local r = rects[i]
        if x >= r[1] and x <= r[3] and y >= r[2] and y <= r[4] then return true end
    end
    return false
end

-- What keeps the chunk: "character", "owned", "legendary", "ruins" or nil.
local function classify(surface, x, y, forces, rects)
    local area = chunk_area(x, y)
    local other = surface.count_entities_filtered{area = area, type = FREE_TYPES, invert = true, limit = 1} > 0
    if other and surface.count_entities_filtered{area = area, type = "character", limit = 1} > 0 then
        return "character"
    end
    if #forces.owned > 0 and surface.count_entities_filtered{area = area, force = forces.owned, limit = 1} > 0 then
        return "owned"
    end
    if in_rects(rects, x, y) then return "legendary" end
    if other then return "ruins" end
    if #forces.ruins > 0 and surface.count_entities_filtered{area = area, force = forces.ruins, limit = 1} > 0 then
        return "ruins"
    end
    return nil
end

-- May the chunk be deleted in the mode?
local function allowed(mode, reason)
    if mode == "force" then return reason ~= "character" end
    return reason == nil
end

