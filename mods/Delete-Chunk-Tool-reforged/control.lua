-- Jobs

local update_tick_handler

local function cancel_job(player_index)
    local job = storage.jobs[player_index]
    if not job then return end
    clear_preview(job)
    storage.jobs[player_index] = nil
    local player = game.get_player(player_index)
    if player then close_dialog(player) end
    update_tick_handler()
end

local function new_job(player, surface, mode)
    cancel_job(player.index)
    local job = {
        player_index = player.index, surface_index = surface.index, mode = mode, state = "scan",
        todo = {}, i = 1, chunks = {}, renders = {}, preview = {},
        stats = {owned = 0, ruins = 0, legendary = 0, character = 0},
        forces = force_sets(), rects = legendary_rects(surface.index),
    }
    storage.jobs[player.index] = job
    return job
end

local function finish_scan(job)
    local player = game.get_player(job.player_index)
    job.state = "preview"
    job.todo, job.rows, job.radars, job.visible = nil, nil, nil, nil
    if not player then return cancel_job(job.player_index) end
    draw_preview(job, job.preview)
    job.preview = nil
    open_dialog(player, job)
end

-- One chunk of the scan: counts the reason and adds the chunk to the preview and the result.
local function scan_chunk(job, surface, c)
    local reason = classify(surface, c.x, c.y, job.forces, job.rects)
    if reason then job.stats[reason] = job.stats[reason] + 1 end
    if job.mode == "trim" then
        if reason == "owned" or reason == "character" then
            job.seeds[#job.seeds + 1] = {x = c.x, y = c.y}
        elseif not reason and surface.get_pollution({c.x * 32 + 16, c.y * 32 + 16}) <= 0 then
            job.chunks[#job.chunks + 1] = {x = c.x, y = c.y}
        end
        return
    end
    if allowed(job.mode, reason) then
        job.chunks[#job.chunks + 1] = {x = c.x, y = c.y}
        job.preview[#job.preview + 1] = {x = c.x, y = c.y, color = reason and "forced" or "free"}
    else
        job.preview[#job.preview + 1] = {x = c.x, y = c.y, color = "kept"}
    end
end

-- Trim: is a free chunk near buildings or radars or seen by a force? Buildings are kept as merged
-- row intervals [x - d, x + d] of the chunks with buildings, so a check reads 2d + 1 rows.
local function trim_keeps(job, surface, c)
    local d = job.distance
    local rows = job.rows
    for y = c.y - d, c.y + d do
        local row = rows[y]
        if row then
            for i = 1, #row, 2 do
                if c.x >= row[i] and c.x <= row[i + 1] then return true end
            end
        end
    end
    for _, r in ipairs(job.radars) do
        if math.abs(c.x - r[1]) <= r[3] and math.abs(c.y - r[2]) <= r[3] then return true end
    end
    for _, force in ipairs(job.visible) do
        if force.valid and force.is_chunk_visible(surface, c) then return true end
    end
    return false
end

local function start_filter(job, surface)
    job.state = "filter"
    job.todo = job.chunks
    job.chunks = {}
    job.i = 1
    -- chunks with buildings: per row the merged intervals {x1, x2, x1, x2, ...} widened by d
    local d, xs = job.distance, {}
    for _, c in ipairs(job.seeds) do
        local row = xs[c.y]
        if not row then
            row = {}
            xs[c.y] = row
        end
        row[#row + 1] = c.x
    end
    local rows = {}
    for y, row in pairs(xs) do
        table.sort(row)
        local merged = {}
        for _, x in ipairs(row) do
            local n = #merged
            if n > 0 and x - d <= merged[n] + 1 then
                merged[n] = x + d
            else
                merged[n + 1], merged[n + 2] = x - d, x + d
            end
        end
        rows[y] = merged
    end
    job.rows = rows
    job.seeds = nil
    -- radars of player forces with the range they chart, in chunks
    local radars = {}
    local found = #job.forces.owned > 0 and surface.find_entities_filtered{type = "radar", force = job.forces.owned} or {}
    for _, radar in pairs(found) do
        local proto, quality = radar.prototype, radar.quality
        local range = math.max(proto.get_max_distance_of_sector_revealed(quality) or 0,
            proto.get_max_distance_of_nearby_sector_revealed(quality) or 0)
        local p = radar.position
        radars[#radars + 1] = {floor(p.x / 32), floor(p.y / 32), range + 1}
    end
    job.radars = radars
    job.visible = {}
    for _, name in ipairs(job.forces.owned) do
        local force = game.forces[name]
        if force and #force.players > 0 then job.visible[#job.visible + 1] = force end
    end
end

local function mark(surface_index, x, y, value)
    local marks = per_surface(storage.marks, surface_index)
    local k = key(x, y)
    if (marks[k] or 0) < value then marks[k] = value end
end

local function delete_one(job, surface, c)
    local reason = classify(surface, c.x, c.y, job.forces, job.rects)
    if not allowed(job.mode, reason) then return false end
    if job.mode == "trim" then
        if surface.get_pollution({c.x * 32 + 16, c.y * 32 + 16}) > 0 then return false end
        mark(surface.index, c.x, c.y, AS_GENERATED)
        per_surface(storage.trimmed, surface.index)[key(c.x, c.y)] = true
    else
        mark(surface.index, c.x, c.y, CLEAN)
    end
    surface.delete_chunk(c)
    for _, force in pairs(game.forces) do force.unchart_chunk(c, surface) end
    return true
end

local function finish_delete(job)
    local player = game.get_player(job.player_index)
    if player then
        player.print({"dct.done", job.deleted, job.skipped})
    end
    clear_preview(job)
    storage.jobs[job.player_index] = nil
    if job.mode == "trim" then storage.trimmed_until = game.tick + LINGER end
end

local function process_job(job)
    local surface = game.get_surface(job.surface_index)
    if not (surface and surface.valid) then
        storage.jobs[job.player_index] = nil
        return
    end
    if job.state == "scan" then
        local todo, last = job.todo, math.min(job.i + SCAN_PER_TICK - 1, #job.todo)
        for i = job.i, last do scan_chunk(job, surface, todo[i]) end
        job.i = last + 1
        if job.i > #todo then
            if job.mode == "trim" then start_filter(job, surface) else finish_scan(job) end
        end
    elseif job.state == "filter" then
        local todo, last = job.todo, math.min(job.i + FILTER_PER_TICK - 1, #job.todo)
        for i = job.i, last do
            local c = todo[i]
            if not trim_keeps(job, surface, c) then
                job.chunks[#job.chunks + 1] = {x = c.x, y = c.y}
                job.preview[#job.preview + 1] = {x = c.x, y = c.y, color = "free"}
            end
        end
        job.i = last + 1
        if job.i > #todo then finish_scan(job) end
    elseif job.state == "delete" then
        local chunks, last = job.chunks, math.min(job.i + DELETE_PER_TICK - 1, #job.chunks)
        for i = job.i, last do
            if delete_one(job, surface, chunks[i]) then job.deleted = job.deleted + 1 else job.skipped = job.skipped + 1 end
        end
        job.i = last + 1
        if job.i > #chunks then finish_delete(job) end
    end
end

local function on_tick()
    for _, job in pairs(storage.jobs) do
        if job.state ~= "preview" then process_job(job) end
    end
    if storage.trimmed_until and game.tick >= storage.trimmed_until then
        local trimming = false
        for _, job in pairs(storage.jobs) do
            if job.mode == "trim" and job.state == "delete" then trimming = true end
        end
        if not trimming then
            storage.trimmed = {}
            storage.trimmed_until = nil
        end
    end
    update_tick_handler()
end

-- on_tick runs only while a job works or the chunks of a trim are still remembered.
function update_tick_handler()
    local busy = storage.trimmed_until ~= nil
    if not busy then
        for _, job in pairs(storage.jobs or {}) do
            if job.state ~= "preview" then busy = true break end
        end
    end
    script.on_event(defines.events.on_tick, busy and on_tick or nil)
end

-- Starts a job and runs its first batch at once: small selections are shown in the same tick.
local function run(job)
    process_job(job)
    update_tick_handler()
end

