--[[ Chunk Delete Tool Reforged - control stage.

Deleting chunks:
* the selection tool (shortcut "chunk-eraser") picks the chunks of the selected area: a normal
  selection keeps chunks with buildings of player forces, ruins and legendary ruins, an alt
  selection (Shift) deletes them too; chunks with a character are never deleted;
* map trimming (shortcut "chunk-trim", command /chunk-trim) picks every chunk of the surface that
  is empty and farther than the "dct-trim-distance" setting from player buildings, outside radar
  range, not visible and without pollution.
The picked chunks are highlighted for the player, a dialog asks to confirm; chunks are classified
and deleted a batch per tick, every chunk is checked again right before it is deleted.

A deleted chunk is regenerated by the map generator when it is needed again. Its storage mark
keeps what was cleared away from coming back:
* ruins: AbandonedRuins_updated_fork, RSO-reforged mines and legendary ruins of
  AbandonedRuins-paranoidal ask remote "is_regenerated" and spawn nothing there;
* ore: the amount of every resource before deletion is kept and the regenerated chunk is cut down
  to it (mined ore does not grow back, ore mined out does not come back);
* enemies: in chunks deleted with the tool the regenerated enemy bases are removed; trimmed chunks
  keep them, as generated.
Remote "count_trimmed" lets MxlChievements-Reforged count only chunks deleted with the tool.
]]

local MOD = "Delete-Chunk-Tool-reforged"
local TOOL = "chunk-eraser"
local TRIM = "chunk-trim"
local GUI = "dct_confirm"

local SCAN_PER_TICK = 128   -- chunks classified per tick
local FILTER_PER_TICK = 256 -- trim candidates checked against buildings and radars per tick
local DELETE_PER_TICK = 64  -- chunks deleted per tick
local MAX_SELECTION = 16384 -- chunks in one selection of the tool
local LINGER = 120          -- ticks the chunks of a finished trim stay known to count_trimmed

-- marks of deleted chunks
local AS_GENERATED = 1 -- regenerated without new ruins, ore capped, enemies as generated
local CLEAN = 2        -- also without enemy bases

-- Entities that do not keep a chunk: nature, enemies and short-lived effects. Everything else of
-- a non-player force (neutral ruin buildings, items on the ground, corpses of characters) does.
local FREE_TYPES = {
    "tree", "simple-entity", "resource", "fish", "cliff", "corpse", "rail-remnants", "fire", "sticker",
    "stream", "projectile", "artillery-projectile", "artillery-flare", "arrow", "beam", "explosion",
    "smoke-with-trigger", "particle-source", "highlight-box", "speech-bubble", "lightning", "asteroid",
    "unit", "unit-spawner", "turret", "spider-unit", "spider-leg", "segmented-unit", "segment",
}
local ENEMY_TYPES = {"unit-spawner", "turret", "unit", "spider-unit", "segmented-unit"}
-- forces of ruins (AbandonedRuins_updated_fork defenders, legendary ruins of AbandonedRuins-paranoidal)
local RUIN_FORCES = {["AbandonedRuins:enemy"] = true, ["pd-legend"] = true}

local floor = math.floor

local function key(x, y) return (x + 32768) * 65536 + (y + 32768) end

local function chunk_area(x, y)
    return {{x * 32, y * 32}, {x * 32 + 32, y * 32 + 32}}
end

local function inside(position, x, y)
    local px, py = position.x - x * 32, position.y - y * 32
    return px >= 0 and px < 32 and py >= 0 and py < 32
end

local function per_surface(root, surface_index)
    local t = root[surface_index]
    if not t then
        t = {}
        root[surface_index] = t
    end
    return t
end

