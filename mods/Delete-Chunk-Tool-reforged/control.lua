commands.add_command("chunk-trim", {"dct.command-help"}, function(command)
    local player = command.player_index and game.get_player(command.player_index)
    if not player then return end
    local distance = tonumber(command.parameter)
    if command.parameter and not (distance and distance >= 1 and distance <= 64) then
        player.print({"dct.command-help"})
        return
    end
    start_trim(player, distance and floor(distance))
end)

remote.add_interface(MOD, {
    -- Was the chunk deleted before (so it is generated again now)? Ruins are not spawned there.
    ---@param surface_index uint
    ---@param position ChunkPosition
    is_regenerated = function(surface_index, position)
        local marks = storage.marks[surface_index]
        return marks ~= nil and marks[key(position.x, position.y)] ~= nil
    end,
    -- How many of the positions were deleted by a map trim (not by the tool)?
    ---@param surface_index uint
    ---@param positions ChunkPosition[]
    count_trimmed = function(surface_index, positions)
        local trimmed = storage.trimmed[surface_index]
        if not trimmed then return 0 end
        local n = 0
        for _, c in pairs(positions) do
            if trimmed[key(c.x, c.y)] then n = n + 1 end
        end
        return n
    end,
})
