--- Generated by Claude
--- Transfers all fluid contents from one entity's fluid storages to another's,
--- using the 2.1 index-based fluid API (LuaEntity:get_fluid/set_fluid/clear_fluid).
--- Matches by FluidStorageIndex; any source index with no corresponding
--- destination index is left alone (fluid stays put, nothing thrown away).
--- @param source LuaEntity
--- @param destination LuaEntity
--- @param clear_source boolean|nil  -- if true (default), clears source storages after copying
--- @return boolean success
function Public.transfer_fluidboxes(source, destination, clear_source)
  if not (source and source.valid and destination and destination.valid) then
    return false
  end

  if clear_source == nil then
    clear_source = true
  end

  -- Neither entity exposes a fluidbox count directly anymore, so probe capacity
  -- to find the number of valid FluidStorageIndex slots on each side.
  local function storage_count(entity)
    local i = 0
    while true do
      local ok, capacity = pcall(function() return entity.get_fluid_capacity(i + 1) end)
      if not ok or capacity == nil then
        break
      end
      i = i + 1
    end
    return i
  end

  local count = math.min(storage_count(source), storage_count(destination))

  for i = 1, count do
    local fluid = source.get_fluid(i) -- {name=..., amount=..., temperature=..., ...} or nil

    if fluid then
      destination.set_fluid(i, fluid)

      if clear_source then
        source.clear_fluid(i)
      end
    end
  end

  return true
end

--- Generated by Claude
--- Copies all wire connections (circuit network wires, copper/power pole wires,
--- power switch wires, combinator input/output wires, etc.) from one entity to another.
--- @param source LuaEntity
--- @param destination LuaEntity
--- @return boolean success
function Public.copy_wire_connections(source, destination)
  if not (source and source.valid and destination and destination.valid) then
    return false
  end

  local source_connectors = source.get_wire_connectors(false)
  if not source_connectors then
    return true -- nothing to copy
  end

  for connector_id, source_connector in pairs(source_connectors) do
    for _, connection in pairs(source_connector.connections) do
      local target = connection.target
      local dest_connector = destination.get_wire_connector(connector_id, true)

      if target.owner == source then
        -- Self-referential wire (e.g. a combinator's input wired to its own
        -- output) — redirect it to the destination's matching connector instead.
        local dest_target = destination.get_wire_connector(target.wire_connector_id, true)
        dest_connector.connect_to(dest_target, true, connection.origin)
      else
        dest_connector.connect_to(target, true, connection.origin)
      end
    end
  end

  return true
end

-- Orientation is a double and the engine's in-place upgrade can introduce a
-- tiny rounding difference (for example 0.635507 becoming
-- 0.63550692377612 for a locomotive on a curve). An exact comparison reports
-- a spurious "orientation mismatch" warning for that save. Treat differences
-- below this tolerance as the same orientation.
local ORIENTATION_TOLERANCE = 1e-4

local function orientations_differ(first, second)
    if first == nil or second == nil then
        return first ~= second
    end
    local difference = math.abs(first - second)
    -- Orientations are in [0, 1); 0.9999 and 0.0001 are adjacent.
    difference = math.min(difference, math.abs(1 - difference))
    return difference > ORIENTATION_TOLERANCE
end

Public.orientations_differ = orientations_differ

--Gets a field of an object, or nil if checking for it normally returns an error.
local function get_field(LuaEntity,field)
    local function get_field_or_error(LuaEntity,field)
        return LuaEntity[field]
    end
    local success,result=pcall(get_field_or_error,LuaEntity,field)
    if success then
        return result
    else
        return nil
    end
    
end

--Transfers all items from all inventories to new_entity, or drops them on the ground if not possible.
function Public.transfer_all_inventories(entity,new_entity)

    for _,inventory_type in pairs(defines.inventory) do
        local inventory = entity.get_inventory(inventory_type)
        local new_inventory = new_entity.get_inventory(inventory_type)
        if inventory and new_inventory then
            new_inventory.transfer_from_inventory(inventory)

            
        end
        
        if inventory and not inventory.is_empty() then
            local items = entity.surface.spill_inventory {
                        position = entity.position,
                        inventory = inventory,
                        enable_looted = true,
                        force = entity.force_index,
                        allow_belts = false
                    }
            
            if entity.force then
                for _,item in pairs(items) do
                    item.order_deconstruction(entity.force)
                end
            end
            
        end
        
    end
end

function Public.get_grid_contents(entity)
    local grid = entity.grid
    if grid then 
        local equipment = grid.equipment 
        local equipment_info = {}
        for _,item in pairs(equipment) do
            local is_ghost = item.name == "equipment-ghost" 
            table.insert(equipment_info,{
                name=is_ghost and item.ghost_name or item.name,
                quality=item.quality.name,
                position = item.position,
                ghost = is_ghost})
        end
        return equipment_info
    end
end

function Public.transfer_grid_contents(entity,new_entity)
    local old_grid = Public.get_grid_contents(entity)
    if old_grid then
        for _,item in pairs(old_grid) do
            new_entity.grid.put{name=item.name,quality = item.quality, position = item.position, ghost = item.ghost}
        end
        
    end

end


--Get inventories from entity, used for rolling stock to hold inventory contents while the two rolling stock are not allowed to coexist.
function Public.get_all_inventories_rolling_stock(entity)
    local returned_inventories = {}
    for _,inventory_type in pairs(defines.inventory) do
        local inventory = entity.get_inventory(inventory_type)
        
        if inventory then
            returned_inventories[inventory_type] = inventory.get_contents()

            
        end
        
        
        
    end
    return returned_inventories
end




--Get fields from entity, used for rolling stock to hold inventory contents while the two rolling stock are not allowed to coexist.
function Public.get_all_fields_rolling_stock(entity)
    local returned_fields = {}
    for field,value in pairs(fields_to_transfer) do
        local field_value = get_field(entity,field)
        --local inventory = entity.get_inventory(inventory_type)
        if field_value then
            returned_fields[field] = field_value  
        end
    end
    --game.print(serpent.block(returned_fields))
    return returned_fields
end

local train_fields = {
    manual_mode = true,
    speed = 0,
    schedule = nil,
    group = nil,
}

function Public.get_train_info(entity)
    local train = entity.train
    local info = {}
    info.carriages = entity.train.carriages
    local front_stock
    local back_stock
    local collect_next_stock = false

    for _,stock in pairs(info.carriages) do
        if collect_next_stock then
            front_stock = stock
            break
        end
        if stock == entity then
            collect_next_stock = true
            last_stock = stock
        end
        
    end
    info.front_stock = entity.get_connected_rolling_stock(defines.rail_direction.front)
    info.back_stock = entity.get_connected_rolling_stock(defines.rail_direction.back)
    info.fields = {}
    info.train = train
    for field,value in pairs(train_fields) do
        info.fields[field] = train[field]
    end
    return info
end

--Returns all information from entity that will be transferred to the replacement entity after this entity is deleted. Used for rolling stock.
function Public.get_info_rolling_stock(entity)
    local info = {}
    info.fields = Public.get_all_fields_rolling_stock(entity)
    info.inventories = Public.get_all_inventories_rolling_stock(entity)
    if entity.type == "fluid-wagon" then
        info.fluid = entity.get_fluid(1)
    end
    
    info.train = Public.get_train_info(entity)
    info.grid = Public.get_grid_contents(entity)
    return info
end

function Public.copy_info_to_new_rolling_stock(new_entity,info)
    local do_rotate
    local orientation 
    for field,value in pairs(info.fields) do
        if field == "orientation" then
            if value >= 0.5 then
                do_rotate = true
                orientation = value
            end
        end
        -- Some fields are read-only for particular rolling-stock types.
        pcall(function()
            new_entity[field] = value
        end)
    end
    if do_rotate then
        --game.print("Train rotated, orientation = "..tostring(orientation))
        new_entity.rotate{}
    end
    
    for inventory_type,inventory_contents in pairs(info.inventories) do
        local inventory =  new_entity.get_inventory(inventory_type)
        if inventory then
            for _,stack in pairs(inventory_contents) do
                inventory.insert(stack)
            end
        else
            for _,stack in pairs(inventory_contents) do
                local items = new_entity.surface.spill_item_stack {
                        position = new_entity.position,
                        stack = stack,
                        enable_looted = true,
                        force = new_entity.force_index,
                        allow_belts = false
                    }
            
                if new_entity.force then
                    for _,item in pairs(items) do
                        item.order_deconstruction(new_entity.force)
                    end
                end
            end
        end
        
    end
    if info.fluid then
        new_entity.set_fluid(1, info.fluid)
    end
    if info.train then
        if info.train.back_stock then
            new_entity.connect_rolling_stock(defines.rail_direction.back)
        end
        if info.train.front_stock then
            new_entity.connect_rolling_stock(defines.rail_direction.front)
        end
        if not info.train.back_stock or info.train.front_stock then
            for field,value in pairs(info.train.fields) do
                new_entity.train[field] = value
            end
            
        end
    end
    if info.grid then
        for _,item in pairs(info.grid) do
            new_entity.grid.put{name=item.name,quality = item.quality, position = item.position, ghost = item.ghost}
        end
    end

end

--Transfers every single entity state, such that the new_entity is the same as the old entity. If a single property is not properly transferred, that is a bug. Exclusions include properties that are destroyed upon fast replaces.
function Public.transfer_entity_state(entity,new_entity)
    new_entity.copy_settings(entity)
    
    for field_to_transfer,default_value in pairs(fields_to_transfer) do
        if get_field(new_entity,field_to_transfer) ~= nil then
            local old_value = get_field(entity,field_to_transfer)
            local value
            if old_value ~= nil then
                value = old_value
            elseif default_value ~= NO_DEFAULT then
                value = default_value
            end
            if value ~= nil then
                -- Some fields (for example is_military_target) exist on every
                -- entity but are read-only for most entity types. Ignore those
                -- instead of aborting the whole replacement.
                pcall(function()
                    new_entity[field_to_transfer] = value
                end)
            end
        end
    end

    for _,tooltip_field in pairs(entity.get_tooltip_fields()) do
        new_entity.set_tooltip_field(tooltip_field)
    end

    Public.transfer_all_inventories(entity,new_entity)
    Public.copy_wire_connections(entity, new_entity)
    Public.transfer_fluidboxes(entity, new_entity, true)
    Public.transfer_grid_contents(entity,new_entity)
end


--Replaces one entity with another, called both on building a new_entity(Or a fast replacement) and on entity migrations.
function Public.replace_entity(entity,new_entity,raise_built)
    if not storage.replaced_entities then storage.replaced_entities = {} end
    if storage.replaced_entities[entity.unit_number] then return end --To stop infinite recursion
    local is_ghost = entity.name == "entity-ghost"
    local name = new_entity
    local player = entity.last_user
    -- Belt-like entities cannot be recreated on top of themselves, so silent
    -- migrations (raise_built = false) use the engine's fast-replace path. This
    -- is what makes reverting an entity-replacement rule work for belts.
    local fast_replace = not raise_built
        and not is_ghost
        and (entity.type == "transport-belt"
            or entity.type == "underground-belt"
            or entity.type == "splitter"
            or entity.type == "loader")
    local old_unit_number = entity.unit_number
    local new_entity_properties = {
        name = is_ghost and "entity-ghost" or name,
        inner_name = is_ghost and name or nil,
        tags = is_ghost and entity.tags or nil,
        position = entity.position,
        direction = entity.direction,
        -- Vehicle ghosts cannot be rotated after creation and expose direction
        -- as north, so pass the smooth orientation when the ghost is created.
        orientation = is_ghost and entity.orientation or nil,
        force = entity.force_index,
        quality = entity.quality,
        health = entity.health,
        raise_built = false, --raise_script_built is called later
        player = raise_built and player or nil,
        mirror = entity.mirroring,
        create_build_effect_smoke = false,
        fast_replace = fast_replace or nil,
    }
    --game.print(entity.ghost_type)
    --if not surface.can_place_entity{new_entity_properties} then return end
    -- if is_ghost and rro.contains({"spider-vehicle","car"},entity.ghost_type) then
    --     game.print("[PlanetsLib] Error: Can not currently place car or spider vehicle entity ghosts on planets with vehicle entity replacement rules. https://tinyurl.com/factorio-car-ghost")
    --     log("[PlanetsLib] Error: Can not currently place car or spider vehicle entity ghosts on planets with vehicle entity replacement rules. https://tinyurl.com/factorio-car-ghost")
    --     entity.destroy()
    --     return 
    -- end
    local train_types= {"locomotive","cargo-wagon","infinity-cargo-wagon","fluid-wagon","artillery-wagon"}
    local is_train = entity.type == "entity-ghost" and rro.contains(train_types,entity.ghost_type) or rro.contains(train_types,entity.type)
    -- Raising script built for an entity that carries equipment ghosts makes
    -- the engine try to place the ghost directly and throw "Equipment is not
    -- equipment-ghost". The grid has already been transferred, so skip only the
    -- notification in that case.
    local has_ghost_equipment = false
    if entity.valid and entity.grid then
        for _, equipment in pairs(entity.grid.equipment) do
            -- Reading ghost_name on a non-ghost equipment throws in the engine.
            if equipment.name == "equipment-ghost" then
                has_ghost_equipment = true
                break
            end
        end
    end
    
    if is_train then
        local old_orientation = entity.orientation
        --print(entity.orientation)
        local surface = entity.surface
        -- Capture rolling-stock state before the old entity is destroyed; the
        -- create fallback below needs it. Ghost rolling stock has no train (and
        -- therefore no inventories or schedule) to capture.
        local rolling_stock_info
        if not is_ghost then
            rolling_stock_info = Public.get_info_rolling_stock(entity)
        end
        local new_entity
        local upgrade_target = {name = name, quality = entity.quality}
        if is_ghost then
            upgrade_target = {name = "entity-ghost", inner_name = name, quality = entity.quality}
        end
        local marked = entity.order_upgrade{target=upgrade_target,force=entity.force}
        if marked then
            new_entity = entity.apply_upgrade()
        else
            -- Custom entity variants are often not valid construction-robot
            -- upgrade targets (they are not an item's place_result), so the
            -- override target may still refuse the in-place upgrade. Fall back
            -- to recreating the rolling stock and restoring its captured state.
            new_entity = entity.apply_upgrade(nil, upgrade_target)
        end
        if not new_entity then
            entity.destroy()
            new_entity = surface.create_entity(new_entity_properties)
            if new_entity and rolling_stock_info then
                Public.copy_info_to_new_rolling_stock(new_entity, rolling_stock_info)
            end
        end
        local orientation_mismatch = false
        if new_entity then
            orientation_mismatch = orientations_differ(old_orientation, new_entity.orientation)
        end
        if orientation_mismatch then
            game.print("Orientation mismatch between locomotive and replacement locomotive! Don't save this game. Report this issue to PlanetsLib."..serpent.block(new_entity.position))
        end
        --print(new_entity.orientation)
        --print(serpent.block(new_entity.train.locomotives))
        
        
        --local new_entity = surface.create_entity(new_entity_properties)

        

        if new_entity and raise_built == true then
            script.raise_script_built{entity=new_entity}
        end
        script.raise_event("PlanetsLib-on-entity-replaced", {
            entity = entity,
            new_entity = new_entity or entity,
        })
        return new_entity, orientation_mismatch
        --Public.transfer_entity_state(entity,new_entity)
    else
        local new_entity = entity.surface.create_entity(new_entity_properties)
        if not new_entity or not new_entity.valid then return end

        if fast_replace then
            -- The engine replaced the old entity in place. Its contents and
            -- settings were handled by fast-replace; do not touch the now
            -- invalid source entity.
            storage.replaced_entities[new_entity.unit_number] = new_entity
            storage.replaced_entities[old_unit_number] = new_entity
            script.raise_event("PlanetsLib-on-entity-replaced", {
                entity = entity,
                new_entity = new_entity,
            })
            if raise_built == true and not has_ghost_equipment then
                script.raise_script_built{entity=new_entity}
            end
            return new_entity
        end

        Public.transfer_entity_state(entity,new_entity)
        -- Modules are moved by transfer_all_inventories (the module inventory is
        -- one of defines.inventory), and any overflow is spilled there. Do not
        -- insert them into the new entity again: that put a second copy in the
        -- crafting output.
        new_entity.last_user = entity.last_user
        storage.replaced_entities[new_entity.unit_number] = new_entity --Important for preventing infinite recursion
        -- Also record the original unit number so other mods can look the
        -- replacement up through the documented get_replacement() interface.
        storage.replaced_entities[entity.unit_number] = new_entity
        script.raise_event("PlanetsLib-on-entity-replaced", {
            entity = entity,
            new_entity = new_entity,
        })
        entity.destroy()
        if raise_built == true and not has_ghost_equipment then
            script.raise_script_built{entity=new_entity}
        end
    end

    
    
    


end

local get_planet = require("lib.entity-replacement-decision-tree.evaluators.planet")

function Public.on_built_entity(event,swap_target,dont_raise_built) -- Based on Maraxsis function. Fulfills rule "If entity X placed on planet Y, replace entity with entity Z"
    local disable_all = settings.startup["PlanetsLib-disable-all-entity-replacements"]
    if disable_all and disable_all.value then return end

    local entity = event.entity
    --if not entity.valid then return end 
    local planet = get_planet(entity)
    local surface = entity.surface
    --if not entity_replacements[planet] then return end
    
    local is_ghost = entity.name == "entity-ghost"
    local name = is_ghost and entity.ghost_name or entity.name

    if not ((entity_replacements_inverted and entity_replacements_inverted[name]) or (entity_replacements[planet] and entity_replacements[planet][name]))  then return end
    
    --print(is_ghost)
    
    local is_space = not not surface.platform
    local swap_target = swap_target or nil
    --game.print(serpent.block(entity_replacements_inverted))
    local is_inverted = false
    if swap_target == nil then
        if entity_replacements_inverted[name] then
            swap_target = entity_replacements_inverted[name]
            is_inverted = true
            if entity_replacements[planet] and entity_replacements[planet][swap_target] then 
                swap_target = entity_replacements[planet][swap_target].entity
            end
        else
            swap_target = entity_replacements[planet][name].entity
        end
    end
    --print(swap_target)
    --print(name)
    if swap_target == name then return end
    if entity_replacements and entity_replacements[planet] and entity_replacements[planet][name] and entity_replacements[planet][name].enabled == false then return end 
        
    Public.replace_entity(entity,swap_target,true)
    

    
    
    



end


